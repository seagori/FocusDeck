  function resolveLang(settingLang) {
    if (settingLang === "ko" || settingLang === "en" || settingLang === "ja") return settingLang;
    const navLang =
      (typeof navigator !== "undefined" && (navigator.language || navigator.userLanguage)) || "en";
    const lower = String(navLang).toLowerCase();
    if (lower.startsWith("ko")) return "ko";
    if (lower.startsWith("ja")) return "ja";
    return "en";
  }

  function t(settingLang, key, vars) {
    const lang = resolveLang(settingLang);
    const dict = MESSAGES[lang] || MESSAGES.en;
    let str = dict[key] !== undefined ? dict[key] : MESSAGES.en[key] || key;
    if (vars && typeof vars === "object") {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      }
    }
    return str;
  }

  function applyDomI18n(settingLang, container) {
    const scope = container || (typeof document !== "undefined" ? document : null);
    if (!scope) return;
    scope.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(settingLang, el.getAttribute("data-i18n"));
    });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(settingLang, el.getAttribute("data-i18n-placeholder")));
    });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => {
      el.setAttribute("title", t(settingLang, el.getAttribute("data-i18n-title")));
    });
  }

  const api = {
    MESSAGES,
    resolveLang,
    t,
    applyDomI18n
  };

  root.XFocusI18n = api;
  if (typeof module !== "undefined" && module.exports) {
    module.exports = api;
  }
